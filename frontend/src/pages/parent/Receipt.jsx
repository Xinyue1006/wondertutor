import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import api, { errorMessage } from '../../api/client'
import { LoadError, Spinner } from '../../components/ui/Common'
import Icon from '../../components/ui/Icon'
import { fmtDate, fmtTimeRange, money } from '../../lib/format'

// A payment receipt the parent can print or save as PDF with the browser (Print > Save as PDF)
export default function Receipt() {
  const { id } = useParams()
  const [r, setR] = useState(null)
  const [error, setError] = useState('')
  const load = () => { setError(''); api.get(`/parent/payments/${id}/receipt`).then((res) => setR(res.data.receipt)).catch((e) => setError(errorMessage(e))) }
  useEffect(load, [id])

  if (error) return <LoadError message={error} onRetry={load} />
  if (!r) return <Spinner />

  const refunded = r.refunds.filter((x) => x.status === 'APPROVED').reduce((t, x) => t + x.amount, 0)
  const row = (label, value) => (
    <div className="flex justify-between gap-6 border-b border-slate-100 py-2.5 text-sm"><dt className="text-slate-500">{label}</dt><dd className="text-right font-semibold text-navy">{value}</dd></div>
  )
  return (
    <div className="mx-auto max-w-xl">
      <div className="mb-4 flex items-center justify-between print:hidden">
        <Link to="/parent/payments" className="flex items-center gap-1 text-sm font-semibold text-brand-500 hover:underline"><Icon name="arrow-left" className="h-4 w-4" /> Back to Payments</Link>
        <button onClick={() => window.print()} className="btn-primary px-5">Print / Save as PDF</button>
      </div>
      <article className="card p-8" aria-label="Payment receipt">
        <header className="flex items-start justify-between border-b border-slate-200 pb-4">
          <div>
            <h1 className="text-2xl font-extrabold text-navy">Payment Receipt</h1>
            <p className="text-sm text-slate-500">WonderTutor · Wonderland Learning Materials &amp; Tuition Centre</p>
          </div>
          <div className="text-right text-sm"><div className="font-bold text-navy">{r.number}</div><div className="text-slate-500">{fmtDate(r.paidAt)}</div></div>
        </header>
        <dl className="mt-2">
          {row('Paid by', `${r.payer.name} (${r.payer.email})`)}
          {row('Lesson', `${r.lesson.subject}${r.lesson.isTrial ? ' (Trial)' : ''} for ${r.lesson.child}`)}
          {row('Tutor', r.lesson.tutor)}
          {row('Date and time', `${fmtDate(r.lesson.startAt)}, ${fmtTimeRange(r.lesson.startAt, r.lesson.endAt)}`)}
          {row('Mode', r.lesson.teachingMode === 'ONLINE' ? 'Online' : 'Physical')}
          {row('Payment method', r.method)}
          {r.reference && row('Payment reference', r.reference)}
          {refunded > 0 && row('Refunded', `− ${money(refunded)}`)}
        </dl>
        <div className="mt-5 flex items-center justify-between rounded-xl bg-brand-50 p-4"><span className="font-bold text-navy">Total paid</span><span className="text-2xl font-extrabold text-navy">{money(r.amount)}</span></div>
        <p className="mt-4 text-xs text-slate-500">This receipt is generated by WonderTutor as proof of payment for the lesson above.</p>
      </article>
    </div>
  )
}
